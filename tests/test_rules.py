# -*- coding: utf-8 -*-
"""规则自测：八类都能挡、还原逐字准、四种正常文字不误伤。不联网、不花钱。"""
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pii_rules import 规则, 新场  # noqa: E402

应挡 = [
    ("手机 +86", "+86 138 0000 6666"),
    ("手机横杠", "138-0000-7777"),
    ("手机纯数字", "13812345678"),
    ("卡号分段", "4111 1111 1111 1111"),
    ("身份证 18", "11010519491231002X"),
    ("老身份证 15", "110105491231003"),
    ("邮箱", "zhang.san+tag@sub.example.com"),
    ("固话", "0571-88888888"),
    ("客服电话", "400-123-4567"),
    ("车牌", "京A12345"),
    ("新能源车牌", "粤BD12345"),
    ("统一社会信用代码", "91350100M000100Y43"),
    ("护照", "E12345678"),
]
不该动 = [
    "订单号 20261124001",
    "价格 4111 元",
    "日期 2026-11-24",
    "时间 14:35",
    "年份 1949 到 2026",
    "普通编号 A1234567",
    "京A123456",        # 8 位、字母后不是 D/F：不是车牌，别吃
]

r = 规则()
好 = 0
for 名, 值 in 应挡:
    场 = 新场()
    原文 = f"这是：{值} 完"
    脱 = r.脱一段(原文, 场)
    挡 = 值 not in 脱
    回 = r.还原一段(脱, 场)
    精确 = 回 == 原文
    print(("✓" if 挡 else "✗"), 名, "→", 脱[:30], "| 还原", 精确)
    好 += 1 if (挡 and 精确) else 0

print()
错 = 0
for 值 in 不该动:
    场 = 新场()
    变 = r.脱一段(值, 场) != 值
    错 += 1 if 变 else 0
    print("  ✗ 误伤" if 变 else "  不动", 值)

# 同一个号出现两次只占一个编号
场 = 新场()
双 = r.脱一段("13812345678 和 13812345678", 场)
同号 = 双.count("[PHONE_1]") == 2 and "[PHONE_2]" not in 双
print("\n同一个号出现两次 →", 双, "| 共用一个占位符", 同号)

print(f"\n应挡 {好}/{len(应挡)}｜误伤 {错}/{len(不该动)}｜同号复用 {同号}")
assert 好 == len(应挡) and 错 == 0 and 同号
